// ---------------------------------------------------------------- INVERTED
// The other side of the twelve regulars (backend challenges.INVERTED_*). Each
// is drawn from its regular's own rows, so the silhouette is the same: a new
// palette turns it over, and a few pixels (cracks, fangs, a grin, a crown) are
// set on top. Patches are [row, column, key] in the left half and land on the
// mirrored column too, so the sprite stays symmetric.

type Patch = [row: number, col: number, key: string];

const flip = (base: PixelArt, palette: Record<string, string>, patches: Patch[] = []): PixelArt => {
  const rows = base.rows.map((row) => [...row]);
  for (const [r, c, key] of patches) {
    const width = rows[r].length;
    rows[r][c] = key;
    rows[r][width - 1 - c] = key;
  }
  return { palette: { ...base.palette, ...palette }, rows: rows.map((row) => row.join('')) };
};

