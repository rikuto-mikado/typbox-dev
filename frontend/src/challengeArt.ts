// Pixel art and colours for the CHALLENGES (BOSS RAID, RIVAL), keyed by the
// boss / rival ids in backend/tracker/challenges.py. Same format as
// buffArt.ts: '.' is transparent, every other character keys the sprite's
// palette. Bosses are 24 x 24 and rival faces 16 x 16, drawn as the left
// half and mirrored, so they stay symmetric.

